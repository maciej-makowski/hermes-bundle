#!/usr/bin/env bash
# Regenerate hermes-pack.yaml, pinned to a full commit SHA.
# A pack installs the plugin half in one reviewed command; skills are not installed by
# packs (the CLI lists them and asks you to install them yourself), so they stay on the tap.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REF="${1:-$(git -C "$ROOT" rev-parse HEAD)}"
case "$REF" in
  *[!0-9a-f]*|"") echo "need a full 40-character lowercase hex sha" >&2; exit 2 ;;
esac
[ "${#REF}" -eq 40 ] || { echo "need a full 40-character sha, got ${#REF} characters" >&2; exit 2; }
cat > "$ROOT/hermes-pack.yaml" <<YAML
# Generated by scripts/make-pack.sh. Regenerate after a release.
# Install: hermes plugins pack show ./hermes-pack.yaml
#          hermes plugins pack install ./hermes-pack.yaml
name: hermes-bundle
description: Hermes extensions, plugin half. Skills install from the tap.
plugins:
  - repo: maciej-makowski/hermes-bundle
    subdir: plugins/design-doc-edit
    ref: $REF
YAML
echo "wrote hermes-pack.yaml pinned to $REF"
